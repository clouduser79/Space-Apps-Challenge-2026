"""GMAT bridge — runs real astrodynamics via GMAT's script mode.

GMAT's Python bindings (gmatpy) only ship up to CPython 3.14, so we
drive the installed GMAT.exe/GmatConsole.exe with generated .script
files and parse the ReportFile output instead.

Typical use:
    from src.game.gmat_bridge import GMATBridge
    data = GMATBridge().orbit_properties("Earth", 400, 51.6)
    # -> {"sma_km": ..., "ecc": ..., "velocity_km_s": ..., "period_min": ...}
"""

from __future__ import annotations

import math
import subprocess
import tempfile
from pathlib import Path

# GMAT install bundled with the repo
GMAT_ROOT = Path(__file__).resolve().parent.parent.parent / "gmat-win-R2026a"
GMAT_BIN = GMAT_ROOT / "bin"
GMAT_CONSOLE = GMAT_BIN / "GmatConsole.exe"
OUTPUT_DIR = GMAT_ROOT / "output"

# Central body -> GMAT force-model primary body name
_BODIES = {
    "Earth": "Earth",
    "Moon": "Luna",
    "Mars": "Mars",
    "Deep Space": "Sun",
}

# Rough GMAT coordinate system per body
_CS = {
    "Earth": "EarthMJ2000Eq",
    "Moon": "MoonMJ2000Eq",
    "Mars": "MarsMJ2000Eq",
    "Deep Space": "SunMJ2000Eq",
}


class GMATBridge:
    """Generates GMAT scripts, runs them headless, parses reports."""

    def __init__(self) -> None:
        self.available = GMAT_CONSOLE.exists()

    # ------------------------------------------------------------------
    # Script generation
    # ------------------------------------------------------------------
    def _script_for_orbit(self, body: str, sma_km: float, ecc: float,
                          inc_deg: float) -> str:
        """Build a GMAT script that propagates one orbit and reports state."""
        primary = _BODIES.get(body, "Earth")
        cs = _CS.get(body, "EarthMJ2000Eq")
        # Propagate ~1.2 orbital periods worth of seconds (rough: LEO ~5400s)
        period_s = 2 * math.pi * math.sqrt(sma_km ** 3 / 398600.4418) \
            if primary == "Earth" else 5400
        prop_secs = period_s * 1.2

        return f"""% Auto-generated by gmat_bridge.py
Create Spacecraft DefaultSC;
DefaultSC.DateFormat = TAIModJulian;
DefaultSC.Epoch = '21545';
DefaultSC.CoordinateSystem = {cs};
DefaultSC.DisplayStateType = Keplerian;
DefaultSC.SMA = {sma_km};
DefaultSC.ECC = {ecc};
DefaultSC.INC = {inc_deg};
DefaultSC.RAAN = 0;
DefaultSC.AOP = 0;
DefaultSC.TA = 0;

Create ForceModel DefaultProp_ForceModel;
DefaultProp_ForceModel.CentralBody = {primary};
DefaultProp_ForceModel.PrimaryBodies = {{{primary}}};

Create Propagator DefaultProp;
DefaultProp.FM = DefaultProp_ForceModel;
DefaultProp.Type = PrinceDormand78;
DefaultProp.InitialStepSize = 60;
DefaultProp.Accuracy = 1e-10;
DefaultProp.MinStep = 0.001;
DefaultProp.MaxStep = 86400;

Create ReportFile rf;
rf.Filename = 'gmat_orbit_report.txt';
rf.WriteHeaders = true;
rf.Add = {{DefaultSC.SMA, DefaultSC.ECC, DefaultSC.RMAG, DefaultSC.VMAG}};

BeginMissionSequence;
Propagate 'Prop orbit' DefaultProp(DefaultSC) {{DefaultSC.ElapsedSecs = {prop_secs:.0f}}};
"""

    # ------------------------------------------------------------------
    # Runner
    # ------------------------------------------------------------------
    def _run_script(self, script: str, report_name: str) -> Path | None:
        """Write script into GMAT bin dir, run console, return report path."""
        if not self.available:
            return None
        script_path = GMAT_BIN / "_game_script.script"
        script_path.write_text(script, encoding="utf-8")
        report_path = OUTPUT_DIR / report_name
        if report_path.exists():
            report_path.unlink()
        try:
            subprocess.run(
                [str(GMAT_CONSOLE), script_path.name],
                cwd=str(GMAT_BIN),
                capture_output=True, timeout=120,
            )
        except (subprocess.TimeoutExpired, OSError):
            return None
        return report_path if report_path.exists() else None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------
    def orbit_properties(self, body: str, altitude_km: float,
                         inclination_deg: float,
                         central_body: str = "Earth") -> dict | None:
        """Propagate a circular-ish orbit in GMAT; return real osculating data.

        Returns dict with sma_km, ecc, radius_km, velocity_km_s, period_min
        or None if GMAT is unavailable/fails.
        """
        # Earth radius ~6378 km; for other bodies use rough values
        radii = {"Earth": 6378.0, "Moon": 1737.4, "Mars": 3396.2,
                 "Deep Space": 0.0}
        r_body = radii.get(body, 6378.0)
        sma_km = r_body + altitude_km if r_body else altitude_km
        if sma_km <= 0:
            return None

        script = self._script_for_orbit(body, sma_km, 0.001, inclination_deg)
        report = self._run_script(script, "gmat_orbit_report.txt")
        if report is None:
            return None
        return self._parse_orbit_report(report)

    @staticmethod
    def _parse_orbit_report(path: Path) -> dict | None:
        """Parse the last data row of the GMAT report file."""
        try:
            lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
        except OSError:
            return None
        # Last non-empty line is the final propagated state
        for line in reversed(lines):
            parts = line.split()
            if len(parts) >= 4:
                try:
                    sma, ecc, rmag, vmag = (float(parts[0]), float(parts[1]),
                                            float(parts[2]), float(parts[3]))
                    period_min = (2 * math.pi * math.sqrt(sma ** 3 / 398600.4418)
                                  / 60) if sma > 0 else 0
                    return {
                        "sma_km": sma,
                        "ecc": ecc,
                        "radius_km": rmag,
                        "velocity_km_s": vmag,
                        "period_min": period_min,
                    }
                except ValueError:
                    continue
        return None


_bridge: GMATBridge | None = None


def get_bridge() -> GMATBridge:
    global _bridge
    if _bridge is None:
        _bridge = GMATBridge()
    return _bridge
